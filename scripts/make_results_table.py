"""Render results/results.md from recorded history + any evaluation runs.

The table is generated, never hand-edited, so a number in it always traces to
either results/history.json (recorded, with provenance) or a run JSON written
by `python -m defectloc.evaluate`. Rows that have not been measured show as
`--` rather than being quietly omitted.

    python scripts/make_results_table.py
"""

import argparse
import json
from pathlib import Path

CONDITIONS = ("clean", "lighting")
METRICS = ("image_AUROC", "pixel_AUROC")


def fmt(v) -> str:
    return "--" if v is None else f"{v:.3f}"


def load_runs(runs_dir: Path, promoted: set[str] | None = None) -> list[dict]:
    """Turn each evaluation run JSON into one table row per scoring variant.

    Runs listed in history's ``promoted_runs`` are skipped: their numbers have
    already been written into the curated rows with an interpretation attached,
    and emitting them twice would put the same measurement in the table under
    two labels.
    """
    promoted = promoted or set()
    rows = []
    for f in sorted(runs_dir.glob("*.json")):
        if f.name in promoted:
            continue
        run = json.loads(f.read_text(encoding="utf-8"))
        for variant, vlabel in (("none", "raw top-k score"), ("median_mad", "median/MAD score")):
            row = {
                "label": f"{run.get('label', f.stem)} ({vlabel})",
                "kind": "ours",
                "source": f"run:{f.name}",
                "provenance": f"produced by defectloc.evaluate from {run.get('checkpoint', '?')}",
                "note": "",
            }
            present = False
            for cond in CONDITIONS:
                c = run.get("conditions", {}).get(cond)
                if c and variant in c.get("variants", {}):
                    row[cond] = {m: c["variants"][variant].get(m) for m in METRICS}
                    present = True
                else:
                    row[cond] = {m: None for m in METRICS}
            if present:
                rows.append(row)
    return rows


def render(history: dict, runs: list[dict]) -> str:
    rows = list(history["rows"]) + runs
    out = []
    out.append("# Results\n")
    out.append(f"**Dataset:** {history['dataset']}\n")
    out.append(
        "A photometric \"factory-lighting\" stress test (brightness / contrast / gamma / "
        "colour drift plus a directional shadow gradient) is applied to the **test set "
        "only**; training stays clean. It measures what happens when a model trained "
        "under one lighting rig meets another.\n"
    )
    out.append("<!-- generated by scripts/make_results_table.py -- do not hand-edit -->\n")

    out.append("| Model | Clean image-AUROC | Clean pixel-AUROC | Lighting image-AUROC | Lighting pixel-AUROC | Source |")
    out.append("|---|:---:|:---:|:---:|:---:|---|")
    for r in rows:
        cells = [fmt(r.get(c, {}).get(m)) for c in CONDITIONS for m in METRICS]
        # Emphasise the headline number: v3's clean pixel-AUROC.
        if r["label"].startswith("Autoencoder v3 -"):
            cells[1] = f"**{cells[1]}**"
        out.append(f"| {r['label']} | " + " | ".join(cells) + f" | {r['source']} |")

    out.append("\n## Provenance\n")
    for r in rows:
        out.append(f"- **{r['label']}** — {r['provenance']}")
        if r.get("note"):
            out.append(f"  - {r['note']}")

    out.append("\n## How to read the two conditions\n")
    out.append(
        "- **image-AUROC** answers *is this bottle defective?* — it ranks whole images.\n"
        "- **pixel-AUROC** answers *where is the defect?* — it ranks individual pixels "
        "against the ground-truth mask, and is the metric this project optimises, since "
        "localisation is the point.\n"
        "- A gap between them is diagnostic. image ≫ pixel means the model knows *whether* "
        "but not *where* (a map-quality problem, which v3 fixed). Pixel healthy but image "
        "at chance means the map is fine and the *score* is broken (a normalisation "
        "problem — the open v3 bug)."
    )
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--history", default="results/history.json")
    p.add_argument("--runs-dir", default="results/runs")
    p.add_argument("--out", default="results/results.md")
    a = p.parse_args(argv)

    history = json.loads(Path(a.history).read_text(encoding="utf-8"))
    runs_dir = Path(a.runs_dir)
    promoted = set(history.get("promoted_runs", []))
    runs = load_runs(runs_dir, promoted) if runs_dir.is_dir() else []

    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(render(history, runs), encoding="utf-8")
    print(f"wrote {a.out}  ({len(history['rows'])} recorded rows, {len(runs)} from runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
